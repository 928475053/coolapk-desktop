import { flushPromises, mount } from '@vue/test-utils';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { createPinia, setActivePinia } from 'pinia';
import { useAuthStore } from '../../../stores/auth';
import EmojiPanel from '../EmojiPanel.vue';
import { CoolapkTauriAPI } from '../../../api/coolapk';
import { clearResourceMemoryCache, loadImageResource } from '../../../utils/resourceCache';
vi.mock('../../../utils/toast', () => ({ showToast: vi.fn() }));
vi.mock('../../../api/coolapk', () => ({ CoolapkTauriAPI: { getEmojiPictures: vi.fn(), getImageDataUrl: vi.fn(), uploadImage: vi.fn(), addEmojiPicture: vi.fn(), editEmojiPictures: vi.fn() } }));
beforeEach(() => { setActivePinia(createPinia()); vi.clearAllMocks(); clearResourceMemoryCache(); });
function login(uid = '123') {
  const auth = useAuthStore(); auth.isLoggedIn = true; auth.user = { uid, username: '测试', userAvatar: '' }; return auth;
}
describe('categorized emoji panel', () => {
  it('exposes official groups and inserts unicode without bracket codes', async () => {
    const wrapper = mount(EmojiPanel);
    expect(wrapper.findAll('[role="tab"]')).toHaveLength(6);
    await wrapper.get('[aria-label="系统 Emoji"]').trigger('click');
    await wrapper.get('.emoji-item-btn').trigger('click');
    expect(wrapper.emitted('select')?.[0]).toEqual(['😀']);
    await wrapper.get('[aria-label="收藏"]').trigger('click');
    expect(wrapper.text()).toContain('登录后查看');
    expect(CoolapkTauriAPI.getEmojiPictures).not.toHaveBeenCalled();
    wrapper.unmount();
  });
  it('selects the existing favorite URL instead of downloading a file to upload again', async () => {
    login();
    vi.mocked(CoolapkTauriAPI.getEmojiPictures).mockResolvedValue({ code: 200, data: [{ id: '1', url: 'https://image.coolapk.com/test.gif' }] });
    vi.mocked(CoolapkTauriAPI.getImageDataUrl).mockResolvedValue('data:image/gif;base64,R0lGODlh');
    const wrapper = mount(EmojiPanel);
    await wrapper.get('[aria-label="收藏"]').trigger('click'); await flushPromises();
    await wrapper.get('.emoji-item-btn').trigger('click'); await flushPromises();
    expect(wrapper.emitted('picture')?.[0]).toEqual([{ id: '1', url: 'https://image.coolapk.com/test.gif' }]);
    expect(CoolapkTauriAPI.uploadImage).not.toHaveBeenCalled();
    wrapper.unmount();
  });
  it('shows load errors and retries instead of showing an empty list as success', async () => {
    login();
    vi.mocked(CoolapkTauriAPI.getEmojiPictures).mockRejectedValueOnce(new Error('network'));
    const wrapper = mount(EmojiPanel);
    await wrapper.get('[aria-label="收藏"]').trigger('click'); await flushPromises();
    expect(wrapper.text()).toContain('加载失败');
    vi.mocked(CoolapkTauriAPI.getEmojiPictures).mockResolvedValue({ code: 200, data: [] });
    await wrapper.get('[role="status"] button').trigger('click'); await flushPromises();
    expect(wrapper.text()).toContain('你还没有添加表情');
    wrapper.unmount();
  });
  it('inserts the image already loaded for the thumbnail without another download', async () => {
    login();
    const url = 'https://image.coolapk.com/cached.jpg';
    vi.mocked(CoolapkTauriAPI.getEmojiPictures).mockResolvedValue({ code: 200, data: [{ id: 'cached', url }] });
    vi.mocked(CoolapkTauriAPI.getImageDataUrl).mockResolvedValue('data:image/jpg;charset=UTF-8;base64,YWJj');
    await loadImageResource(url, CoolapkTauriAPI.getImageDataUrl);
    const wrapper = mount(EmojiPanel);
    await wrapper.get('[aria-label="收藏"]').trigger('click'); await flushPromises();
    expect(wrapper.findComponent({ name: 'AppImage' }).exists()).toBe(true);
    await wrapper.get('.emoji-item-btn').trigger('click'); await flushPromises();
    expect(CoolapkTauriAPI.getImageDataUrl).toHaveBeenCalledTimes(1);
    expect(wrapper.emitted('picture')?.[0]).toEqual([{ id: 'cached', url }]);
    wrapper.unmount();
  });
  it('blocks a duplicate selection but allows adding again after removal', async () => {
    login();
    vi.mocked(CoolapkTauriAPI.getEmojiPictures).mockResolvedValue({ code: 200, data: [{ id: 'retry', url: 'https://image.coolapk.com/retry.gif' }] });
    vi.mocked(CoolapkTauriAPI.getImageDataUrl).mockRejectedValue(new Error('HTTP 403'));
    const wrapper = mount(EmojiPanel, { props: { selectedUrls: ['https://image.coolapk.com/retry.gif'] } });
    await wrapper.get('[aria-label="收藏"]').trigger('click'); await flushPromises();
    await wrapper.get('.emoji-item-btn').trigger('click'); await flushPromises();
    expect(wrapper.emitted('picture')).toBeUndefined();
    await wrapper.setProps({ selectedUrls: [] });
    await wrapper.get('.emoji-item-btn').trigger('click'); await flushPromises();
    expect(wrapper.emitted('picture')).toHaveLength(1);
    expect(wrapper.emitted('picture')?.[0]).toEqual([{ id: 'retry', url: 'https://image.coolapk.com/retry.gif' }]);
    wrapper.unmount();
  });
  it('ignores an old account response after switching accounts', async () => {
    const auth = login(); let finish!: (value: unknown) => void;
    vi.mocked(CoolapkTauriAPI.getEmojiPictures).mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
    const wrapper = mount(EmojiPanel);
    await wrapper.get('[aria-label="收藏"]').trigger('click');
    vi.mocked(CoolapkTauriAPI.getEmojiPictures).mockResolvedValue({ code: 200, data: [] });
    auth.user = { uid: '456', username: '另一个账号', userAvatar: '' }; await flushPromises();
    finish({ code: 200, data: [{ id: 'old', url: 'https://image.coolapk.com/old.gif' }] }); await flushPromises();
    expect(wrapper.find('.emoji-item-btn').exists()).toBe(false);
    expect(wrapper.text()).toContain('你还没有添加表情');
    wrapper.unmount();
  });
  it('refreshes automatically when entering favorites again and returning to the window', async () => {
    login();
    vi.mocked(CoolapkTauriAPI.getEmojiPictures).mockResolvedValue({ code: 200, data: [] });
    const wrapper = mount(EmojiPanel);
    await wrapper.get('[aria-label="收藏"]').trigger('click'); await flushPromises();
    expect(wrapper.text()).not.toContain('刷新收藏');
    expect(wrapper.find('[aria-label="添加收藏表情"]').exists()).toBe(true);
    await wrapper.get('[aria-label="酷安表情"]').trigger('click');
    await wrapper.get('[aria-label="收藏"]').trigger('click'); await flushPromises();
    expect(CoolapkTauriAPI.getEmojiPictures).toHaveBeenCalledTimes(2);
    window.dispatchEvent(new Event('focus')); await flushPromises();
    expect(CoolapkTauriAPI.getEmojiPictures).toHaveBeenCalledTimes(3);
    wrapper.unmount();
    window.dispatchEvent(new Event('focus')); await flushPromises();
    expect(CoolapkTauriAPI.getEmojiPictures).toHaveBeenCalledTimes(3);
  });
  it('uploads GIFs to the official emoji directory, adds them, and refreshes', async () => {
    login();
    vi.mocked(CoolapkTauriAPI.getEmojiPictures).mockResolvedValue({ code: 200, data: [] });
    vi.mocked(CoolapkTauriAPI.uploadImage).mockResolvedValue({ code: 200, data: 'https://image.coolapk.com/added.gif' });
    vi.mocked(CoolapkTauriAPI.addEmojiPicture).mockResolvedValue({ code: 200, data: 'ok' });
    const wrapper = mount(EmojiPanel);
    await wrapper.get('[aria-label="收藏"]').trigger('click'); await flushPromises();
    const file = new File(['GIF'], 'test.gif', { type: 'image/gif' });
    Object.defineProperty(file, 'arrayBuffer', { value: async () => new Uint8Array([71, 73, 70]).buffer });
    const input = wrapper.get('input[type="file"]');
    Object.defineProperty(input.element, 'files', { configurable: true, value: [file] });
    await input.trigger('change'); await flushPromises();
    expect(CoolapkTauriAPI.uploadImage).toHaveBeenCalledWith(new Uint8Array([71, 73, 70]), 'test.gif', 'image/gif', 'feed_emoji_picture');
    expect(CoolapkTauriAPI.addEmojiPicture).toHaveBeenCalledWith('https://image.coolapk.com/added.gif');
    expect(CoolapkTauriAPI.getEmojiPictures).toHaveBeenCalledTimes(2);
    expect(wrapper.emitted('picture')).toBeUndefined();
    wrapper.unmount();
  });
  it('saves ordered IDs and deletes selected IDs without inserting a picture', async () => {
    login();
    const pictures = [{ id: '1', url: 'https://image.coolapk.com/1.gif' }, { id: '2', url: 'https://image.coolapk.com/2.gif' }];
    vi.mocked(CoolapkTauriAPI.getEmojiPictures).mockResolvedValue({ code: 200, data: pictures });
    vi.mocked(CoolapkTauriAPI.editEmojiPictures).mockResolvedValue({ code: 200, data: 'ok' });
    vi.mocked(CoolapkTauriAPI.getImageDataUrl).mockResolvedValue('data:image/gif;base64,R0lGODlh');
    const wrapper = mount(EmojiPanel);
    await wrapper.get('[aria-label="收藏"]').trigger('click'); await flushPromises();
    await wrapper.get('.emoji-manager-heading button').trigger('click');
    const items = wrapper.findAll('[aria-label="选择收藏表情"]');
    const elementFromPoint = vi.fn().mockReturnValue(items[1].element);
    Object.defineProperty(document, 'elementFromPoint', { configurable: true, value: elementFromPoint });
    const down = new Event('pointerdown', { bubbles: true });
    Object.assign(down, { pointerId: 1, button: 0, clientX: 10, clientY: 10 }); items[0].element.dispatchEvent(down);
    const move = new Event('pointermove', { cancelable: true });
    Object.assign(move, { pointerId: 1, clientX: 80, clientY: 10 }); window.dispatchEvent(move);
    const up = new Event('pointerup'); Object.assign(up, { pointerId: 1 }); window.dispatchEvent(up);
    await items[0].trigger('click');
    expect(wrapper.text()).toContain('已选 0 个');
    expect(wrapper.find('[aria-label="表情后移"]').exists()).toBe(false);
    await wrapper.get('.emoji-manager-actions button:last-child').trigger('click'); await flushPromises();
    expect(CoolapkTauriAPI.editEmojiPictures).toHaveBeenCalledWith('sort', ['2', '1']);
    await wrapper.findAll('[aria-label="选择收藏表情"]')[0].trigger('click');
    await wrapper.get('.emoji-manager-actions button').trigger('click'); await flushPromises();
    expect(CoolapkTauriAPI.editEmojiPictures).toHaveBeenCalledWith('delete', ['1']);
    expect(wrapper.emitted('picture')).toBeUndefined();
    wrapper.unmount();
  });
});
